export type ThemeMode = 'dark' | 'light' | 'system'
export type ProcessingMode = 'offline' | 'online' | 'auto'

export interface Settings {
  version: number
  general: {
    language: string
    restoreLastProject: boolean
    confirmDelete: boolean
    showTips: boolean
  }
  appearance: {
    theme: ThemeMode
    accent: string
    density: 'comfortable' | 'compact'
    timelineClipHeight: number
    reduceMotion: boolean
  }
  storage: {
    workspaceRoot: string
    defaultImportMode: 'managed' | 'linked'
    keepProxies: boolean
  }
  ai: {
    mode: ProcessingMode
    defaultProviderId?: string
    transcriptionProviderId?: string
    analysisProviderId?: string
    visionProviderId?: string
    /** Model overrides; empty means "use the provider default". */
    textModel?: string
    transcriptionModel?: string
    /** Vision (frame sampling) is opt-in — frames leave the machine only if enabled. */
    allowVision: boolean
    /** Transcript text may be sent to the configured provider for scoring. */
    allowTranscriptUpload: boolean
    /** Legacy flag kept so older settings files still load. */
    allowUploadWithoutConfirm: boolean
  }
  transcription: {
    language: string
    autoDetect: boolean
    speakerLabels: boolean
    wordTimestamps: boolean
    threads: number
    defaultModel: string
  }
  performance: {
    proxyEnabled: boolean
    proxyHeight: number
    hardwareAcceleration: boolean
    previewQuality: 'full' | 'half' | 'quarter'
    maxConcurrentJobs: number
  }
  export: {
    presetId: string
    outputDir: string
    defaultResolution: '720p' | '1080p' | '1440p' | 'dci2k' | '4k'
    defaultFps: number
    /** Constant rate factor: lower is higher quality. */
    crf: number
    hardwareEncoder: boolean
    burnCaptions: boolean
    writeSidecarSubtitles: boolean
    validateAfterExport: boolean
  }
  updates: {
    autoCheck: boolean
    intervalHours: number
    channel: 'stable' | 'prerelease'
  }
  /**
   * Explicit binaries chosen by the user when automatic detection fails.
   * An empty string means "auto-detect" for that tool.
   */
  tools: {
    whisperPath: string
    ffmpegPath: string
    /** yt-dlp executable, needed to import pages such as YouTube links. */
    ytdlpPath: string
  }
  shortcuts: Record<string, string>
  privacy: {
    telemetry: false
    keepLocalHistory: boolean
  }
  /** Local UI state that belongs with the user's preferences. */
  setup: {
    firstRunCompleted: boolean
  }
}

