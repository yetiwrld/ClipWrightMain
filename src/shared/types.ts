/* ------------------------------------------------------------------ */
/* Clips & tracks                                                     */
/* ------------------------------------------------------------------ */

export type TrackKind = 'video' | 'image' | 'audio' | 'text' | 'caption' | 'graphic'

export interface ClipTransform {
  x: number
  y: number
  scale: number
  scaleX: number
  scaleY: number
  rotation: number
  opacity: number
  cropL: number
  cropR: number
  cropT: number
  cropB: number
}

export interface AudioProps {
  volume: number
  /** dB gain applied on top of volume, -24..+24 */
  gainDb: number
  fadeInMs: number
  fadeOutMs: number
  muted: boolean
  /** Draw the waveform in the timeline. */
  showWaveform: boolean
  /** Simple 3-band balance. 0 = neutral. */
  bass: number
  treble: number
  pan: number
  normalize: boolean
  ducking: boolean
}

export type ClipKind = 'video' | 'image' | 'audio' | 'text' | 'caption' | 'graphic'

export interface Clip {
  id: string
  kind: ClipKind
  trackId: string
  assetId?: string
  name: string
  /** Timeline start, ms. */
  start: number
  /** Timeline duration, ms. */
  duration: number
  /** Offset into the source media, ms. */
  sourceIn: number
  /** Source duration where applicable (ms) — used to clamp trims. */
  sourceDuration?: number
  playing: boolean
  locked?: boolean
  groupId?: string
  color?: string

  transform: ClipTransform
  keyframes: KeyframeTracks
  effects: Effect[]
  transitionIn?: Transition
  transitionOut?: Transition
  audio: AudioProps

  /* text / caption payloads */
  text?: string
  style?: TextStyle
  layout?: TextBoxLayout
  animation?: CaptionAnimation
  animationDurationMs?: number
  /** Caption clips carry word-level timing so karaoke/highlight styles work. */
  words?: CaptionWord[]
  /** For caption clips created from a preset. */
  captionPresetId?: string
  /** How words are highlighted within a caption clip. */
  highlightMode?: 'none' | 'keyword' | 'spoken'
  /** Precomputed emphasis word indices for keyword highlighting. */
  keywordIndices?: number[]
  /** Graphic clips reference a built-in icon name. */
  iconName?: string
  /** SVG markup for imported vector graphics. */
  svg?: string
}

export interface Track {
  id: string
  kind: TrackKind
  name: string
  height: number
  visible: boolean
  locked: boolean
  muted: boolean
  solo: boolean
  opacity: number
  /** Blend mode used when compositing this track in the export pipeline. */
  blend?: 'normal' | 'screen' | 'multiply' | 'overlay'
}

