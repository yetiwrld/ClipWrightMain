/**
 * Clipwright Studio — shared domain types.
 * Used by the main process (media engine, AI, storage) and the renderer (editor UI).
 * All times are expressed in milliseconds unless the field name says otherwise.
 */

/* ------------------------------------------------------------------ */
/* Media                                                              */
/* ------------------------------------------------------------------ */

export type MediaKind = 'video' | 'audio' | 'image'

export interface MediaProbe {
  kind: MediaKind
  durationMs: number
  width?: number
  height?: number
  fps?: number
  /** Detected variable frame rate (average fps differs from r_frame_rate). */
  vfr?: boolean
  rotation?: number
  videoCodec?: string
  audioCodec?: string
  hasAudio: boolean
  sampleRate?: number
  channels?: number
  bitrate?: number
  container?: string
  displayAspect?: string
  pixFmt?: string
}

export interface MediaAsset {
  id: string
  name: string
  /** Absolute path on disk. Always present for managed and referenced assets. */
  path: string
  /** Relative path inside the project's media folder when the asset is managed. */
  relativePath?: string
  kind: MediaKind
  /** 'managed' = copied into the project's media library, 'linked' = referenced in place. */
  storage: 'managed' | 'linked'
  probe: MediaProbe
  probeError?: string
  importedAt: number
  /** Thumbnail file path (generated by the media engine). */
  thumbnail?: string
  /** Normalised audio peaks file used to draw waveforms. */
  waveform?: string
  /** Optional proxy file for heavy sources. */
  proxy?: string
  proxyStatus?: 'none' | 'queued' | 'building' | 'ready' | 'failed'
  /** Set when the file could not be located at its recorded path. */
  missing?: boolean
  /** Import source descriptor, e.g. local file or remote URL. */
  source?: { type: 'file' | 'url'; url?: string; pageUrl?: string; title?: string }
  tags?: string[]
  sizeBytes?: number
}

/* ------------------------------------------------------------------ */
/* Keyframes                                                          */
/* ------------------------------------------------------------------ */

export type EasingKind =
  | 'linear'
  | 'easeIn'
  | 'easeOut'
  | 'easeInOut'
  | 'step'
  | 'bezier'

export interface Easing {
  kind: EasingKind
  /** cubic-bezier control points, only used when kind === 'bezier' */
  cp?: [number, number, number, number]
}

export interface Keyframe {
  id: string
  /** Offset from the clip's start, in ms. */
  t: number
  value: number
  easing: Easing
}

/** Animatable numeric properties of a clip. */
export type AnimatableProp =
  | 'x'
  | 'y'
  | 'scale'
  | 'scaleX'
  | 'scaleY'
  | 'rotation'
  | 'opacity'
  | 'volume'
  | 'cropL'
  | 'cropR'
  | 'cropT'
  | 'cropB'

export type KeyframeTracks = Partial<Record<AnimatableProp, Keyframe[]>>

